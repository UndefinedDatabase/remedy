"""`docs/system/sandbox-model.md` is the sandbox profile and enforcement records rendered, every
row linked to the test that proves it (DECISION F162 D8).

The document is GENERATED by `render_sandbox_model()` in `scripts/render_sandbox_model.py`, the
same `docs/guides/environment.md` pattern `tests/docs/test_environment_guide.py` pins. This walk
proves the LINK in both directions (the F043 two-direction pattern): every node id a Proof cell
names resolves to a defined test, read by parsing the file rather than by running it; and every
fixture-process test of both runner test files — one that takes `sandbox_ready` or
`container_ready` and so starts a real sandboxed process or container — is named by at least one
row. The suite that runs the named tests proves their colour; this walk only proves the link.
"""
from __future__ import annotations

import ast
import re
from pathlib import Path

from scripts.render_sandbox_model import SANDBOX_MODEL_DOC_PATH, render_sandbox_model

REPO_ROOT = Path(__file__).resolve().parents[2]
DOC = REPO_ROOT / SANDBOX_MODEL_DOC_PATH
REGENERATE = "python3 scripts/render_sandbox_model.py"

#: A Proof cell's node id: one of the two runner test files, then `::`, then a bare function name
#: or a `Class::method` pair.
_NODE_ID_RE = re.compile(r"(tests/orchestration/test_sandbox_(?:profiles|container)\.py)::([\w:]+)")


def _defined_node_ids(path: Path) -> set[str]:
    """Every `func` and `Class::method` pytest could collect from *path*, read by parsing it."""
    if not path.is_file():
        return set()
    tree = ast.parse(path.read_text(encoding="utf-8"))
    ids: set[str] = set()
    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            ids.add(node.name)
        elif isinstance(node, ast.ClassDef):
            for item in node.body:
                if isinstance(item, (ast.FunctionDef, ast.AsyncFunctionDef)):
                    ids.add(f"{node.name}::{item.name}")
    return ids


def unresolved_proof_node_ids(doc_text: str, repo_root: Path) -> list[str]:
    """Every `<path>::<id>` the Proof column names that does not resolve to a defined test."""
    unresolved: list[str] = []
    defined_by_path: dict[str, set[str]] = {}
    for rel_path, suffix in _NODE_ID_RE.findall(doc_text):
        if rel_path not in defined_by_path:
            defined_by_path[rel_path] = _defined_node_ids(repo_root / rel_path)
        if suffix not in defined_by_path[rel_path]:
            unresolved.append(f"{rel_path}::{suffix}")
    return unresolved


def _fixture_process_test_ids(path: Path, rel_path: str, fixture_name: str) -> set[str]:
    """Every node id of a test in *path* that takes *fixture_name* — it starts a real sandboxed
    process or container, rather than only computing against stand-in records."""
    if not path.is_file():
        return set()
    tree = ast.parse(path.read_text(encoding="utf-8"))
    ids: set[str] = set()
    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            params = {a.arg for a in node.args.args} | {a.arg for a in node.args.kwonlyargs}
            if fixture_name in params:
                ids.add(f"{rel_path}::{node.name}")
        elif isinstance(node, ast.ClassDef):
            for item in node.body:
                if isinstance(item, (ast.FunctionDef, ast.AsyncFunctionDef)):
                    params = {a.arg for a in item.args.args} | {a.arg for a in item.args.kwonlyargs}
                    if fixture_name in params:
                        ids.add(f"{rel_path}::{node.name}::{item.name}")
    return ids


def uncovered_fixture_process_tests(
        doc_text: str, profiles_path: Path, container_path: Path) -> list[str]:
    """Every fixture-process test of both runner files that no row's Proof column names."""
    ids = (
        _fixture_process_test_ids(
            profiles_path, "tests/orchestration/test_sandbox_profiles.py", "sandbox_ready")
        | _fixture_process_test_ids(
            container_path, "tests/orchestration/test_sandbox_container.py", "container_ready")
    )
    return sorted(node_id for node_id in ids if node_id not in doc_text)


def test_the_committed_document_equals_the_rendering():
    assert DOC.is_file(), DOC
    assert DOC.read_text(encoding="utf-8") == render_sandbox_model(), (
        f"{SANDBOX_MODEL_DOC_PATH} differs from the rendering; regenerate it with {REGENERATE}")


def test_every_proof_node_id_resolves_to_a_defined_test():
    unresolved = unresolved_proof_node_ids(render_sandbox_model(), REPO_ROOT)
    assert unresolved == []


def test_every_fixture_process_test_is_named_by_at_least_one_row():
    doc_text = render_sandbox_model()
    uncovered = uncovered_fixture_process_tests(
        doc_text,
        REPO_ROOT / "tests/orchestration/test_sandbox_profiles.py",
        REPO_ROOT / "tests/orchestration/test_sandbox_container.py")
    assert uncovered == []


def test_a_document_naming_a_nonexistent_node_id_fails_the_resolution_check(tmp_path):
    test_dir = tmp_path / "tests" / "orchestration"
    test_dir.mkdir(parents=True)
    (test_dir / "test_sandbox_profiles.py").write_text(
        "def test_real():\n    pass\n", encoding="utf-8")
    doc_text = (
        "process: tests/orchestration/test_sandbox_profiles.py::test_does_not_exist; "
        "container: none")
    unresolved = unresolved_proof_node_ids(doc_text, tmp_path)
    assert unresolved == ["tests/orchestration/test_sandbox_profiles.py::test_does_not_exist"]


def test_no_row_reads_prevents_nothing_to_limit():
    # DECISION F162 D9: a run cannot go beyond a value the profile never declares, so no cell may
    # tell a reader the runner "prevents" that; such a cell reads "no limit declared" instead.
    doc_text = render_sandbox_model()
    assert "prevents — nothing to limit" not in doc_text


def test_a_fixture_test_no_row_names_fails_the_coverage_check(tmp_path):
    test_dir = tmp_path / "tests" / "orchestration"
    test_dir.mkdir(parents=True)
    profiles_path = test_dir / "test_sandbox_profiles.py"
    profiles_path.write_text(
        "def test_a_real_fixture(tmp_path, sandbox_ready):\n    pass\n", encoding="utf-8")
    container_path = test_dir / "test_sandbox_container.py"
    container_path.write_text("def test_nothing():\n    pass\n", encoding="utf-8")
    doc_text = "no proof cell in this stand-in document names anything"
    uncovered = uncovered_fixture_process_tests(doc_text, profiles_path, container_path)
    assert uncovered == ["tests/orchestration/test_sandbox_profiles.py::test_a_real_fixture"]
