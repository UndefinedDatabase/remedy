"""`docs/system/permission-matrix-v1.md` is the permission matrix rendered (DECISION F141 D6 (1)).

The page is GENERATED by `render_permission_matrix_page()` in
`packages/orchestration/permission_matrix.py`. A constant change that is not re-rendered leaves a
page that names a row the matrix no longer has, or misses one it does — exactly the drift this
test exists to end, so the committed bytes must equal the rendering.
"""
from __future__ import annotations

from pathlib import Path

from packages.orchestration import permission_matrix as pm

REPO_ROOT = Path(__file__).resolve().parents[2]
PAGE = REPO_ROOT / pm.PERMISSION_MATRIX_PAGE_PATH
REGENERATE = (
    'python3 -c "from packages.orchestration.permission_matrix import '
    'write_permission_matrix_page; write_permission_matrix_page()"'
)


def test_the_committed_page_is_the_matrix_rendered():
    assert PAGE.is_file(), PAGE
    assert PAGE.read_text(encoding="utf-8") == pm.render_permission_matrix_page(), (
        f"{pm.PERMISSION_MATRIX_PAGE_PATH} differs from the matrix; regenerate it with "
        f"{REGENERATE}"
    )


def test_every_action_names_its_row_in_both_tables():
    text = PAGE.read_text(encoding="utf-8")
    for action in pm.PERMISSION_ACTIONS:
        assert text.count(f"| `{action}` |") == 2, action


def test_an_action_removed_from_the_constant_leaves_both_tables(monkeypatch):
    trimmed = tuple(a for a in pm.PERMISSION_ACTIONS if a != "expensive")
    monkeypatch.setattr(pm, "PERMISSION_ACTIONS", trimmed)
    rendering = pm.render_permission_matrix_page()
    assert "| `expensive` |" not in rendering
    assert rendering.count("| `read` |") == 2


def test_the_page_is_indexed_in_both_tables_of_the_docs_index():
    index = (REPO_ROOT / "docs" / "README.md").read_text(encoding="utf-8")
    assert index.count("](system/permission-matrix-v1.md)") == 2


def test_permission_seams_has_exactly_the_actions_keys():
    assert set(pm.PERMISSION_SEAMS) == set(pm.PERMISSION_ACTIONS)
