    # Pipe show-job output to a temp file so Python can parse it without
    # calling remedy again via a nested subprocess from within the script.
    _TMP_JOB="$(mktemp)"
    remedy show-job "${JOB_ID}" > "${_TMP_JOB}"
    python3 -c "
