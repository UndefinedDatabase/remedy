" "${TARGET_REPO}" "${APPLIED_TARGET}" "${FIRST_INTENT_ID}"

        # 6f. verify exact run-log schema for patch_intent_applied events
        echo "--- 6f. Verify run-log schema (patch_intent_applied)"
        python3 -c "
