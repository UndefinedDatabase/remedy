#!/usr/bin/env bash
# remedy_smoke.sh — Project Registry + Brain Viewer smoke test.
#
# Usage (source):
#   source scripts/remedy_smoke.sh
#   remedy_smoke
#
# Usage (direct):
#   ./scripts/remedy_smoke.sh
#
# Requirements: remedy CLI on PATH, python3.
# Optional: Ollama running locally (for run-next-task-local).
#
# Overrides:
#   REMEDY_SMOKE_REPO  — temp repo path (default: /tmp/remedy-target-repo)
#
# TARGET_REPO is recreated fresh on each run (rm -rf + mkdir).  The whole-repo
# markerless scan (step 7g) is therefore a developer smoke invariant that proves
# Remedy's own writes contain no raw "<!--" HTML comments or "Generated by Remedy"
# provenance strings.  It is not a runtime policy for arbitrary user repos.

remedy_smoke() {
  (
    set -euo pipefail

    local TARGET_REPO="${REMEDY_SMOKE_REPO:-/tmp/remedy-target-repo}"
    local PROMPT="${1:-Create exactly one task with task_type write_readme: Write a README for a small internal CLI tool. No further tasks.}"

    # Resolve run-log root: $REMEDY_DATA_DIR/runs or .data/runs (public filesystem convention)
    local RUNS_ROOT
    if [[ -n "${REMEDY_DATA_DIR:-}" ]]; then
        RUNS_ROOT="${REMEDY_DATA_DIR}/runs"
    else
        RUNS_ROOT=".data/runs"
    fi

    # -------------------------------------------------------------------------
    # 1. Create target repo
    # -------------------------------------------------------------------------
    echo "--- 1. Create target repo: ${TARGET_REPO}"
    rm -rf "${TARGET_REPO}"
    mkdir -p "${TARGET_REPO}"

    cat >"${TARGET_REPO}/AGENTS.md" <<'AGENTS_EOF'
# Test Target Repo
AGENTS_EOF

    # Makefile with test target using python3 -c (no pytest required).
    # The Project Constitution will extract "make test" from this file,
    # making it the highest-priority discovered test command.
    cat >"${TARGET_REPO}/Makefile" <<'MAKEFILE_EOF'
.PHONY: test build lint

test:
	python3 -c "import sys; print('make test: smoke ok'); sys.exit(0)"

build:
	python3 -c "print('build ok')"

lint:
	python3 -c "print('lint ok')"
MAKEFILE_EOF

    cat >"${TARGET_REPO}/pyproject.toml" <<'PYPROJECT_EOF'
[project]
name = "smoke-target"
version = "0.1.0"

[tool.pytest.ini_options]
testpaths = ["tests"]
PYPROJECT_EOF

    # package.json with pnpm-lock.yaml to prove JS package-manager discovery.
    cat >"${TARGET_REPO}/package.json" <<'PKG_EOF'
{
  "name": "smoke-target",
  "scripts": {
    "test": "echo 'no js tests' && exit 0",
    "build": "echo 'no js build' && exit 0"
  }
}
PKG_EOF
    touch "${TARGET_REPO}/pnpm-lock.yaml"

    # Subprojects to prove multi-ecosystem bounded scan.
    mkdir -p "${TARGET_REPO}/rust-lib"
    cat >"${TARGET_REPO}/rust-lib/Cargo.toml" <<'CARGO_EOF'
[package]
name = "smoke-rust-lib"
version = "0.1.0"
edition = "2021"
CARGO_EOF

    mkdir -p "${TARGET_REPO}/go-service"
    cat >"${TARGET_REPO}/go-service/go.mod" <<'GOMOD_EOF'
module smoke-go-service

go 1.21
GOMOD_EOF

    mkdir -p "${TARGET_REPO}/jvm-app"
    cat >"${TARGET_REPO}/jvm-app/build.gradle" <<'GRADLE_EOF'
plugins {
    id 'java'
}
test {
    useJUnitPlatform()
}
GRADLE_EOF

    # Seed README.md (modify-action apply target).
    cat >"${TARGET_REPO}/README.md" <<'README_EOF'
# Tiny Internal Tool

Initial README content.

## Proposed Update

Smoke-test placeholder.
README_EOF

    # Seed tests/ for pyproject pytest discovery.
    mkdir -p "${TARGET_REPO}/tests"
    cat >"${TARGET_REPO}/tests/test_readme.py" <<'TEST_EOF'
